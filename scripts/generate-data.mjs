// Generates the FICTIONAL, synthetic INSIGHT360 dataset. No real people are represented.
import { writeFileSync } from 'node:fs'
let s = 360
const rnd = () => ((s = (s * 1664525 + 1013904223) % 4294967296) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const clamp = (n, lo, hi) => Math.max(lo, Math.min(hi, Math.round(n)))
const cohorts = [
  ['2025-Q1-A', '2025-01-13'], ['2025-Q1-B', '2025-02-10'], ['2025-Q2-A', '2025-04-07'],
  ['2025-Q2-B', '2025-05-12'], ['2025-Q3-A', '2025-07-14'], ['2025-Q3-B', '2025-08-11'],
]
const programs = ['New Manager Foundations', 'Platform Adoption Sprint', 'Consulting Onboarding Pathway']
const roles = ['Analyst', 'Consultant', 'Senior Consultant', 'People Manager', 'Operations Associate']
const modes = ['Virtual', 'In person', 'Blended']
const rows = []
for (let i = 1; i <= 72; i++) {
  const [cohort] = cohorts[(i - 1) % cohorts.length]
  const ci = (i - 1) % cohorts.length
  const program = programs[Math.floor(((i - 1) / 6) % 3)]
  const completed = rnd() > 0.17 - ci * 0.01
  const participation = clamp(55 + rnd() * 40 + ci * 1.5, 30, 100)
  const pre = clamp(48 + rnd() * 24, 30, 90)
  const post = completed ? clamp(pre + 12 + rnd() * 20 + ci, 40, 100) : ''
  const sat = completed ? clamp(3.2 + rnd() * 1.7, 1, 5) : ''
  rows.push({
    learner_id: `SYN-${String(i).padStart(3, '0')}`, program, cohort, role: pick(roles), delivery_mode: pick(modes),
    enrolled: 'Yes', completed: completed ? 'Yes' : 'No', participation_pct: participation,
    pre_score: pre, post_score: post, satisfaction_1_5: sat,
    manager_observed_application: completed ? (rnd() > 0.45 ? 'Yes' : 'Not yet') : '',
  })
}
// Deliberate, disclosed data-quality issues for the data-quality-check demonstration.
rows[13].post_score = ''; rows[13].completed = 'Yes'
rows[40].participation_pct = 130
rows[55].learner_id = rows[54].learner_id
const cols = Object.keys(rows[0])
const csv = [cols.join(','), ...rows.map((r) => cols.map((c) => r[c]).join(','))].join('\n') + '\n'
writeFileSync('public/downloads/insight360-synthetic-learners.csv', csv)
writeFileSync('src/data/learners.json', JSON.stringify({
  notice: 'Entirely synthetic and fictional. Generated by scripts/generate-data.mjs with a fixed seed. No real learners.',
  records: rows.map((r) => ({ ...r, participation_pct: +r.participation_pct, pre_score: +r.pre_score, post_score: r.post_score === '' ? null : +r.post_score, satisfaction_1_5: r.satisfaction_1_5 === '' ? null : +r.satisfaction_1_5 })),
}, null, 1))
console.log(`wrote ${rows.length} records`)
